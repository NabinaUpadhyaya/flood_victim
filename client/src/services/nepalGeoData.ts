/**
 * Returns list of all 77 districts
 */
export function getDistricts(): string[] {
  return Object.keys(NEPAL_GEO_DATA);
}

/**
 * Returns municipalities for a given district
 */
export function getMunicipalities(district: string): Municipality[] {
  return NEPAL_GEO_DATA[district] ?? [];
}

/**
 * Returns the ward count for a given municipality within a district
 */
export function getWardCount(district: string, municipalityName: string): number {
  const muns = getMunicipalities(district);
  const found = muns.find((m) => m.name === municipalityName);
  return found?.wards ?? 0;
}

/**
 * Returns an array of ward numbers [1, 2, ..., n] for the given municipality
 */
export function getWards(district: string, municipalityName: string): number[] {
  const count = getWardCount(district, municipalityName);
  return Array.from({ length: count }, (_, i) => i + 1);
}
